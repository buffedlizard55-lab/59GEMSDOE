"""Build the static site from the evidence: pages, feed, feed script and preview figure.

Why generated and not hand-written: a page that quotes a number by hand goes stale
the moment the number changes, and stale numbers are exactly what the standing
brief forbids.  Everything here is derived from the receipts on disk at build
time, so re-running this script after any rebuild refreshes the whole site.

Outputs
-------
* ``docs/research.html``    -- rendered ``docs/research/*.md`` (method, hypotheses, instruments)
* ``docs/sources.html``     -- rendered ``docs/research/sources.md`` (every source + status)
* ``docs/results.html``     -- the current numbers: candidate, clearance, holdout CI, board, negatives
* ``docs/irregularities.html`` -- rendered ``docs/research/irregularities.md``
* ``docs/assets/site.js``   -- fetches ``data/run_card.json`` / ``data/leaderboard.json`` and fills the
  status strip, so the published status is the file's status and nobody has to check by hand
* ``docs/data/leaderboard.json``  -- the leaderboard snapshot, with the row revisions kept
* ``docs/assets/preview.png``     -- the shipped dots over the mapped catalogue, 4x block-downsampled

Usage: python scripts/build_site_pages.py
"""
