def _fix_links(html_text: str, md_dir: Path) -> str:
    """Make the markdown's relative links resolve from the rendered page.

    ``../../evidence/x.json`` -> ``data/x.json`` (and the file is copied there);
    ``why-02778.md`` -> ``research/why-02778.md``.
    """
    text = re.sub(r'href="(?:\.\./)*evidence/([^"]+)"', r'href="data/\1"', html_text)
    text = re.sub(r'href="(?!https?://|#|/|data/|research/|index\.html|executive-summary\.html|method\.html|'
                  r'data-sources\.html|results\.html|sources\.html|irregularities\.html|downloads/)'
                  r'([A-Za-z0-9._-]+\.(?:md|json|html))"', r'href="research/\1"', text)
    return text


def _mirror_referenced(referenced: set[str]) -> None:
    for name in referenced:
        src = ROOT / "evidence" / name
        if src.is_file():
            (DOCS / "data" / name).write_bytes(src.read_bytes())


