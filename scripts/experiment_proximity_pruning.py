#!/usr/bin/env python3
"""H6-1: paired holdout test of visible-catalogue proximity pruning.

One predeclared experiment. For each outer spatial fold, fit the retained E2
relay+bend arm using the other three folds, allocate dots exactly as in the
shared Session-5 pipeline, then compare:

* proximity_prune: remove every allocated dot <=2 px from the VISIBLE catalogue;
* random_prune: remove the same number of allocated dots using a fixed RNG.

The held-out truth is never used for fitting, allocation, pruning, or choosing
the removal count. It is read only by the shared evaluator after both masks are
fixed. No submission is generated by this experiment.
"""
from __future__ import annotations

import gc
import json
import os
from pathlib import Path
import sys
import time

os.environ.setdefault("OMP_NUM_THREADS", "2")
os.environ.setdefault("OPENBLAS_NUM_THREADS", "2")
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

import numpy as np
from scipy import ndimage as ndi
from threadpoolctl import threadpool_limits

from gems59 import evaluate_holdout as EH
from gems59 import load_grid
from gems59.anatomy import FEATURES
from gems59.emit import greedy_allocate
from gems59.faultzone import trace_sense_raster
from gems59.fitting import fit_model
from gems59.holdout import FOLD_NAMES, buffered_component_draw
from gems59.relay_bend_anatomy import (
    ALL_RELAY_BEND_FEATURES, BEND_FEATURES, RELAY_FEATURES,
    build_relay_bend_geometry, cached_scarp_geometry,
)

COLS = {n: i for i, n in enumerate(ALL_RELAY_BEND_FEATURES)}
ARM_COLS = ([COLS[n] for n in FEATURES if n != "side"]
            + [COLS[n] for n in BEND_FEATURES]
            + [COLS[n] for n in RELAY_FEATURES])


def subset(g, selected, key):
    from types import SimpleNamespace
    return SimpleNamespace(X=g.X[selected], y=g.y[selected], rows=g.rows[selected],
                           cols=g.cols[selected], key=key,
                           feature_names=ALL_RELAY_BEND_FEATURES)


def predict(clf, scale, g, shape, zone_px):
    p = np.zeros(shape, np.float32)
    for start in range(0, len(g.y), 150_000):
        sl = slice(start, min(start + 150_000, len(g.y)))
        x = g.X[sl]
        v = np.clip(clf.predict_proba(x[:, ARM_COLS])[:, 1] * scale, 0, 1).astype(np.float32)
        v[x[:, 0] > zone_px] = 0
        p[g.rows[sl], g.cols[sl]] = v
    return p


def main() -> int:
    started = time.monotonic()
    grid = load_grid()
    folds, quad = buffered_component_draw(grid, seed=20)
    visible = folds[0]["visible"]
    hidden = folds[0]["hidden_all"]
    domain = np.logical_or.reduce([f["region"] for f in folds]) & ~folds[0]["masked_known"]
    sense = trace_sense_raster(ROOT / "data/external/trace_segments_utm11.csv",
                               grid.shape, grid.transform)
    scarp = cached_scarp_geometry(ROOT, grid.footprint)
    full = build_relay_bend_geometry(grid, visible, hidden, domain, sense, scarp,
                                     ROOT / ".cache/relay_bend_geometry",
                                     "draw20-buffered")
    geoms = [subset(full, quad[full.rows, full.cols] == q, FOLD_NAMES[q]) for q in range(4)]

    terms = {"unpruned": None, "proximity_prune": None, "random_prune": None}
    per_fold = []
    for q, fold in enumerate(folds):
        train = [g for i, g in enumerate(geoms) if i != q]
        distances = np.concatenate([g.X[g.y == 1, 0] for g in train])
        zone = float(np.quantile(distances, .90))
        fraction = float((distances <= zone).mean())
        cap = max(1, int(10_000 * fraction))
        n_train = sum(len(g.y) for g in train)
        n_pos = sum(int(g.y.sum()) for g in train)
        allowed = fold["region"] & ~fold["masked_known"]
        k_est = (n_pos / n_train) * float(allowed.sum())
        test = geoms[q]
        with threadpool_limits(limits=2):
            clf, scale, _ = fit_model(train, seed=q, cols=ARM_COLS)
            p = predict(clf, scale, test, grid.shape, zone)
        allowed_zone = allowed.copy()
        far = test.X[:, 0] > zone
        allowed_zone[test.rows[far], test.cols[far]] = False
        allocation = greedy_allocate(p, allowed_zone, k_truth=k_est, floor=.015,
                                     max_dots=cap)
        base = allocation.emitted
        distance_visible = ndi.distance_transform_edt(~fold["visible"])
        remove = base & (distance_visible <= 2.0)
        candidate = base & ~remove

        y, x = np.nonzero(base)
        rng = np.random.default_rng(20261010 + q)
        picked = rng.choice(len(y), size=int(remove.sum()), replace=False)
        random_mask = base.copy()
        random_mask[y[picked], x[picked]] = False

        fold_row = {"fold": FOLD_NAMES[q], "allocated": int(base.sum()),
                    "removed": int(remove.sum()), "training_zone_px": zone,
                    "truth_used_for_pruning": False, "arms": {}}
        for name, mask in (("unpruned", base), ("proximity_prune", candidate),
                           ("random_prune", random_mask)):
            score, spatial = EH.evaluate(mask.astype(np.float32), fold, grid.footprint)
            terms[name] = spatial if terms[name] is None else terms[name] + spatial
            fold_row["arms"][name] = {k: score[k] for k in
                                      ("dti", "tpw", "fpw", "fnw", "n_truth", "n_emitted")}
        per_fold.append(fold_row)
        print(FOLD_NAMES[q], {n: round(fold_row["arms"][n]["dti"], 6) for n in terms},
              "removed", int(remove.sum()), flush=True)
        del p, allocation, clf, distance_visible
        gc.collect()

    pooled = EH.pooled_summary(terms, draws=1000, seed=20261010,
                               candidate="proximity_prune")
    canary = json.loads((ROOT / "evidence/relay_bend_canary.json").read_text())
    distance_canary = canary["features"]["d"]
    delta = pooled["paired_differences"]["random_prune"]
    promoted = delta["ci95"][0] > 0 and not distance_canary["leakage_flag"]
    report = {
        **pooled,
        "experiment_id": "H6-1",
        "hypothesis": "Removing allocated dots within 2 px of the visible training catalogue improves DTI more than matched random pruning.",
        "split_version": "buffered-whole-components-loqo-v2",
        "pruning_radius_px": 2.0,
        "random_seed_by_fold": [20261010 + q for q in range(4)],
        "distance_feature_canary": distance_canary,
        "per_fold": per_fold,
        "holdout_scope_limitation": {
            "nearest_visible_to_any_withheld_truth_px": float(folds[0]["receipt"]["nearest_visible_to_truth_px"]),
            "feature_context_buffer_px": int(folds[0]["receipt"]["feature_buffer_px"]),
            "implication": "The buffered holdout contains no withheld truth within 3 px of visible catalogue context. It can evaluate the allocator after <=2 px pruning, but it cannot identify the live near-catalogue new-fault regime that motivated H6-1. Treat failure to promote as inconclusive for that regime, not proof that proximity pruning never helps live labels."
        },
        "promotion_rule": "paired 95% CI lower bound for proximity_prune minus random_prune > 0 and canary AUC <= 0.90",
        "promotion_rule_passed": promoted,
        "verdict": "promote-to-uniqueness-gate" if promoted else "negative",
        "submission_slots_used": 0,
        "runtime_seconds": time.monotonic() - started,
    }
    out = ROOT / "evidence/h6_1_proximity_pruning_holdout.json"
    out.write_text(json.dumps(report, indent=2, allow_nan=False) + "\n")
    print(json.dumps({"scores": pooled["scores"], "paired": pooled["paired_differences"],
                      "promotion_rule_passed": promoted}, indent=2), flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
